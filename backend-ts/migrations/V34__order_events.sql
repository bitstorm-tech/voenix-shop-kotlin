-- The order history (issue #282, decision D5 of the Operations package guide).
--
-- One row per transition that overwrites a column or has an actor: the placement, a payment start,
-- a payment status change, the paid and the cancelled transition, a SPOD state the partner
-- reported, and a shipment. Each is written in the transaction of the transition it describes and
-- only when that transition changed something. Facts with their own timestamp column (a processed
-- request, a generated or prepared job, a delivered file, a sent mail) are read from that column
-- and are not repeated here. The table is append-only and owned by the order module; production
-- writes its two events through the order module's `recordEvent`.
--
-- `actor_id` is the user behind an `ADMIN` or `SUPPLIER` event; `cause` says what drove a system
-- event (`WEBHOOK`, `REFRESH`, ...); `details` holds only bounded fields, never provider text.

CREATE TABLE order_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    kind varchar(64) NOT NULL,
    actor_type varchar(16) NOT NULL,
    actor_id bigint,
    cause varchar(64),
    details jsonb,
    CONSTRAINT pk_order_events PRIMARY KEY (id),
    CONSTRAINT fk_order_events_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_events_actor_type
        CHECK (actor_type IN ('SYSTEM', 'CUSTOMER', 'ADMIN', 'SUPPLIER', 'CHANNEL'))
);
CREATE INDEX ix_order_events_order_id ON order_events (order_id, id);
