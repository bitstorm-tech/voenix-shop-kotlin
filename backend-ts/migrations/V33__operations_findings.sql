-- The operations findings (issue #282, decisions D2 and D3 of the Operations package guide).
--
-- The operations worker asks the order, production, and email modules every five minutes which of
-- their rows stand still, and records each answer here. One row is one finding: a kind, the row it
-- is about (`subject_type`, `subject_id`), the order it belongs to when known, and since when the
-- row is stuck. A scan refreshes `last_seen_at`, `attempt_count`, and `last_error_code` of a
-- finding it reports again and keeps `first_seen_at`; it sets `resolved_at` on every open finding
-- it did not report. The partial unique index allows one *open* finding per kind and subject, so a
-- finding that resolved and reappears is a new row, and the resolved ones stay as history.
--
-- `order_id` carries no foreign key: the table is a record of what the scan saw, owned by the
-- operations module, and must never stop an order from being deleted. `alerted_at` is written by
-- the alert mail, which follows in a later step.

CREATE TABLE operations_findings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    kind varchar(64) NOT NULL,
    subject_type varchar(16) NOT NULL,
    subject_id bigint NOT NULL,
    order_id bigint,
    since timestamptz NOT NULL,
    attempt_count integer,
    last_error_code varchar(64),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    alerted_at timestamptz,
    resolved_at timestamptz,
    CONSTRAINT pk_operations_findings PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ux_operations_findings_open
    ON operations_findings (kind, subject_type, subject_id) WHERE resolved_at IS NULL;
CREATE INDEX ix_operations_findings_order_id ON operations_findings (order_id);

-- So that a mail can be attributed to an order: the order confirmation, the producer notification,
-- and the shipping notification store their order's id. No foreign key either: the email module is
-- a leaf, and a deleted order must not fail an unrelated job. The index serves the per-order read.
ALTER TABLE email_jobs ADD COLUMN order_id bigint;
CREATE INDEX ix_email_jobs_order_id ON email_jobs (order_id);
