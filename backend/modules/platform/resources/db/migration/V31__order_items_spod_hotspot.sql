-- The SPOD hotspot an order line was placed with (issue #260, decisions 8 and 14).
--
-- A hotspot is the partner's named placement on the front of a product, such as
-- `MEDIUM_FRONT`. The sync measures one per product type and the live editor shows the
-- customer exactly that frame. What is printed must be what was previewed, so the
-- hotspot is snapshotted on the line at placement like the names and the mug
-- measurements around it: a later sync that picks a different hotspot cannot change
-- what an already placed order asks the partner for.
--
-- It is `NULL` for every line that is not a SPOD article — a mug has no hotspot.
ALTER TABLE order_items ADD COLUMN spod_hotspot varchar(64) NULL;
