-- Access tokens (issue #293): the second way to authenticate, for an AI client on the MCP endpoint
-- and the admin routes that opt in with `requireAdminOrToken`. An admin creates a named token in the
-- dashboard; only the SHA-256 hash of the token is stored, the plain token leaves the server once.
-- A token has no expiry: deleting its row revokes it at once. It acts as the user who created it,
-- with that user's roles read on every request, and goes away with the user.
CREATE TABLE access_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    name character varying(100) NOT NULL,
    token_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    CONSTRAINT pk_access_tokens PRIMARY KEY (id),
    CONSTRAINT ck_access_tokens_name_not_empty CHECK (name <> ''),
    CONSTRAINT ux_access_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_access_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
