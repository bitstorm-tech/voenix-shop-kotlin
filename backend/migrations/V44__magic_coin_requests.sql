-- Magic Coin refill requests submitted by signed-in customers when their balance reaches zero,
-- plus an explicit blocklist for accounts rejected permanently by an admin.
CREATE TABLE magic_coin_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    status text NOT NULL,
    granted_coins integer,
    blocked_user boolean NOT NULL DEFAULT false,
    decided_by_user_id bigint,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at timestamptz,
    CONSTRAINT pk_magic_coin_requests PRIMARY KEY (id),
    CONSTRAINT fk_magic_coin_requests_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_magic_coin_requests_decided_by
        FOREIGN KEY (decided_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_magic_coin_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_magic_coin_requests_granted_coins
        CHECK (
            (status = 'APPROVED' AND granted_coins > 0)
            OR (status <> 'APPROVED' AND granted_coins IS NULL)
        ),
    CONSTRAINT ck_magic_coin_requests_blocked_user
        CHECK (status = 'REJECTED' OR blocked_user = false),
    CONSTRAINT ck_magic_coin_requests_decided_at
        CHECK (
            (status = 'PENDING' AND decided_at IS NULL)
            OR (status <> 'PENDING' AND decided_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX ux_magic_coin_requests_pending_user
    ON magic_coin_requests (user_id)
    WHERE status = 'PENDING';

CREATE INDEX ix_magic_coin_requests_user_id
    ON magic_coin_requests (user_id, created_at DESC, id DESC);

CREATE INDEX ix_magic_coin_requests_status_created_at
    ON magic_coin_requests (status, created_at DESC, id DESC);

CREATE TABLE magic_coin_request_blocks (
    user_id bigint NOT NULL,
    blocked_by_user_id bigint,
    blocked_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_magic_coin_request_blocks PRIMARY KEY (user_id),
    CONSTRAINT fk_magic_coin_request_blocks_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_magic_coin_request_blocks_blocked_by
        FOREIGN KEY (blocked_by_user_id) REFERENCES users (id) ON DELETE SET NULL
);
